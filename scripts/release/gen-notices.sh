#!/bin/sh
# 生成 THIRD-PARTY-NOTICES.md（阶段 5A t5c）。
#
# 数据来源：
#   1) `cargo metadata`（宿主 + x86_64-pc-windows-gnu 两个解析结果取并集）里的每个 crate：
#      名称、版本、许可证表达式；
#   2) 每个 crate 源码目录里的 LICENSE* 文件（取第一段文本，缺失则标注）；
#   3) libghostty（ghostty 上游，vendored 为 vendor/libghostty-rs，固定 commit 见 docs/BUILDING.md）；
#   4) 随附 ConPTY 的许可证（scripts/windows/conpty/LICENSE-ConPTY.txt）。
#
# 任一依赖为 GPL/LGPL/AGPL，或完全没有许可证信息 → 打印清单并以 1 退出（停止发布，交人工判断）。
set -eu

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH='' cd -- "$SCRIPT_DIR/../.." && pwd)
cd "$ROOT"

command -v python3 >/dev/null 2>&1 || { echo "需要 python3 解析 cargo metadata（仅脚本用，非运行时依赖）" >&2; exit 1; }

cargo metadata --format-version 1 > /tmp/leantty-meta-host.json
cargo metadata --format-version 1 --filter-platform x86_64-pc-windows-gnu > /tmp/leantty-meta-win.json

python3 - "$ROOT" <<'PY'
import json, os, sys, glob

root = sys.argv[1]
host = json.load(open('/tmp/leantty-meta-host.json'))
win = json.load(open('/tmp/leantty-meta-win.json'))

def collect(meta):
    out = {}
    for p in meta['packages']:
        if p.get('source') is None:      # 本仓库自己的 crate
            continue
        key = (p['name'], p['version'])
        out[key] = p
    return out

pkgs = collect(host)
pkgs.update(collect(win))

rows = []
bad, missing = [], []
for (name, ver), p in sorted(pkgs.items()):
    lic = p.get('license') or (', '.join(p.get('license_file', []) or []))
    if not lic:
        lic = '<none>'
        missing.append(f'{name} {ver}')
    # 许可证表达式按 SPDX 语义判断：`A OR B` 只要存在不含 GPL 的选项即可选它；
    # 只有"所有备选都含 GPL"（或 AND 组里含 GPL）才视为必须停止发布的情形。
    parts = [x.strip().strip('()') for x in lic.split(' OR ')]
    if all('GPL' in x.upper() for x in parts):
        bad.append(f'{name} {ver} ({lic})')
    rows.append((name, ver, lic, p.get('manifest_path', '')))

lines = []
lines.append('# Third-party notices')
lines.append('')
lines.append('leantty is distributed under the MIT license (see LICENSE). It is built with the')
lines.append('following third-party components; their license texts follow in the appendix.')
lines.append('')
lines.append('Generated by `scripts/release/gen-notices.sh` from `cargo metadata`')
lines.append('(host platform plus the `x86_64-pc-windows-gnu` target).')
lines.append('')
lines.append('## Components')
lines.append('')
lines.append('| Component | Version | License |')
lines.append('|---|---|---|')
for name, ver, lic, _ in rows:
    lines.append(f'| {name} | {ver} | {lic} |')

lines.append('')
lines.append('## First-party dependencies')
lines.append('')
lines.append('- **libghostty (ghostty)** — VT parsing and terminal state, vendored as')
lines.append('  `vendor/libghostty-rs`. MIT licensed. Upstream: https://github.com/ghostty-org/ghostty')
lines.append('  (commit pinned in `docs/BUILDING.md`).')
lines.append('- **Bundled ConPTY (Windows builds only)** — see the appendix below.')

lines.append('')
lines.append('## License texts')
lines.append('')
seen = set()
for name, ver, lic, manifest in rows:
    if lic in seen:
        continue
    seen.add(lic)
    lines.append(f'### {lic}')
    lines.append('')
    d = os.path.dirname(manifest) if manifest else ''
    files = sorted(glob.glob(os.path.join(d, 'LICENSE*')) + glob.glob(os.path.join(d, 'COPYING*')))
    if not files:
        lines.append('_License file not present in the crate source; license expression above applies._')
        lines.append('')
        continue
    for f in files[:1]:
        text = open(f, encoding='utf-8', errors='replace').read().strip()
        lines.append('```text')
        lines.append(text)
        lines.append('```')
        lines.append('')

conpty = os.path.join(root, 'scripts/windows/conpty/LICENSE-ConPTY.txt')
lines.append('### Bundled ConPTY (Windows)')
lines.append('')
if os.path.exists(conpty):
    lines.append('```text')
    lines.append(open(conpty, encoding='utf-8', errors='replace').read().strip())
    lines.append('```')
else:
    lines.append('`scripts/windows/conpty/LICENSE-ConPTY.txt` not found; the bundled ConPTY binaries')
    lines.append('come from Microsoft Windows Terminal and are MIT licensed.')

open(os.path.join(root, 'THIRD-PARTY-NOTICES.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

if bad:
    print('发现 GPL/LGPL/AGPL 依赖，停止：\n  ' + '\n  '.join(bad), file=sys.stderr)
    sys.exit(1)
if missing:
    print('发现无许可证信息的依赖，停止：\n  ' + '\n  '.join(missing), file=sys.stderr)
    sys.exit(1)
print(f'已生成 THIRD-PARTY-NOTICES.md（{len(rows)} 个第三方 crate）')
PY
